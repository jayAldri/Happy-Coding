document.addEventListener("DOMContentLoaded", function () {
  const posts = document.querySelectorAll(".post");
  const postsPerPage = 12;
  const pagination = document.getElementById("pagination");

  let currentPage = 1;
  const totalPages = Math.ceil(posts.length / postsPerPage);

  function showPage(page) {
    currentPage = page;

    posts.forEach((post, index) => {
      post.style.display =
        index >= (page - 1) * postsPerPage &&
        index < page * postsPerPage
          ? "block"
          : "none";
    });

    renderPagination();
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  function renderPagination() {
    pagination.innerHTML = "";

    // Prev button
    pagination.appendChild(createPageItem("«", currentPage - 1, currentPage === 1));

    // Page numbers
    for (let i = 1; i <= totalPages; i++) {
      pagination.appendChild(createPageItem(i, i, false, i === currentPage));
    }

    // Next button
    pagination.appendChild(
      createPageItem("»", currentPage + 1, currentPage === totalPages)
    );
  }

  function createPageItem(text, page, disabled = false, active = false) {
    const li = document.createElement("li");
    li.className = "page-item";

    if (disabled) li.classList.add("disabled");
    if (active) li.classList.add("active");

    const a = document.createElement("a");
    a.className = "page-link";
    a.href = "#";
    a.innerText = text;

    a.addEventListener("click", function (e) {
      e.preventDefault();
      if (!disabled) showPage(page);
    });

    li.appendChild(a);
    return li;
  }

  showPage(1); // Initial load
});




